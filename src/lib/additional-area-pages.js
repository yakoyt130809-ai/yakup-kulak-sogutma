function createAreaPage({
  slug,
  name,
  side,
  neighborhoods,
  context,
  serviceFocus,
  businesses,
}) {
  const lowerName = name.toLocaleLowerCase("tr-TR");
  const lastVowel = [...lowerName].reverse().find((letter) => "aeıioöuü".includes(letter));
  const softSuffix = "eiöü".includes(lastVowel) ? "de" : "da";
  const lastLetter = lowerName.at(-1);
  const suffix = "çfhkpsşt".includes(lastLetter)
    ? softSuffix.replace("d", "t")
    : softSuffix;
  const location = `${name}'${suffix}`;

  return {
    slug,
    name,
    side,
    title: `${name} Soğuk Oda ve Ticari Buzdolabı Tamiri`,
    metaTitle: `${name} Soğuk Oda ve Ticari Dolap Tamiri`,
    metaDescription: `${location} soğuk oda, market dolabı ve sanayi tipi buzdolabı tamiri. ${serviceFocus} için İstanbul genelinde yerinde ticari soğutma servisi.`,
    intro: `${location} market, restoran, üretim, konaklama ve gıda işletmelerinde kullanılan soğuk oda ile ticari dolaplar için yerinde servis talebi alıyoruz.`,
    localContext: [
      context,
      `${serviceFocus} için cihaz türü, mevcut sıcaklık ve hata bilgisi alınır. Yerinde kontrolde fan, sensör, defrost, elektrik beslemesi, kompresör ve soğutma devresi ölçülerek arızanın kaynağı belirlenir.`,
    ],
    neighborhoods,
    businesses,
    advantages: [
      `${name} mahallelerinde yerinde servis planlaması`,
      `${serviceFocus} için ölçümlü arıza tespiti`,
      "Elektrik ve soğutma devresinin birlikte kontrolü",
      "Onay sonrası onarım ve sıcaklık doğrulaması",
    ],
    faq: [
      {
        q: `${location} hangi soğutma sistemlerine servis veriyorsunuz?`,
        a: "Soğuk oda, market ve sütlük dolabı, kasap ve pastane teşhir dolabı ile dik veya tezgâh tipi sanayi tipi buzdolaplarında arıza tespiti, tamir ve bakım yapıyoruz.",
      },
      {
        q: `${name} için yerinde arıza tespiti yapılır mı?`,
        a: `Evet. ${name} mahallelerinde cihaz türü, konum ve ekip uygunluğuna göre yerinde servis planlanır. İşlem ve parça ihtiyacı tespit sonrasında açıklanır.`,
      },
      {
        q: "Dolap soğutmuyorsa servis gelene kadar ne yapılmalı?",
        a: "Ürünleri güvenli sıcaklıktaki başka bir dolaba alın; cihazı art arda açıp kapatmayın. Ekrandaki sıcaklığı, hata kodunu ve çalışma sesini servis talebinde paylaşın.",
      },
    ],
  };
}

